from __future__ import annotations


def _lst(v):
    """Coerce a bare string to a one-element list; None to []."""
    if not v:
        return []
    return [v] if isinstance(v, str) else list(v)


def C(name, desc, founded, stage, total, rnd, lead, inv, hc, hq, bm, fnd, target, diff, rel, url):
    """Compact company-entry builder (order matters — see the fields below)."""
    return {
        "name": name, "one_line_description": desc, "founded_year": founded,
        "funding_stage": stage, "total_funding_disclosed": total, "last_round": rnd,
        "lead_investors": _lst(lead), "investors": _lst(inv),
        "headcount": hc, "hq": hq, "business_model": bm,
        "founders": _lst(fnd), "target_customer": target, "key_differentiator": diff,
        "related_companies": _lst(rel), "source_urls": [url],
        "citations": {"general": url},
    }


